"""Lossless Python 2 interned strings and context-sensitive references."""

import io
from struct import pack

import pytest
from xdis.load import load_module_from_file_object
from xdis.magics import by_version, magic2int
from xdis.marsh import dumps
from xdis.unmarshal import VersionIndependentUnmarshaller, load_code


def string_record(tag, value):
    size = bytes([len(value)]) if tag == b"Z" else pack("<i", len(value))
    return tag + size + value


def reader(data, version="2.7"):
    return VersionIndependentUnmarshaller(
        io.BytesIO(data), magic2int(by_version[version]), False, code_objects={}
    )


@pytest.mark.parametrize("version", ("2.4", "2.7"))
@pytest.mark.parametrize(
    "value",
    (b"", b"ascii_value", b"a\0b", b"\xffA\x80", b"\xc3\xa9", bytes(range(256))),
    ids=("empty", "ascii", "nul", "non-utf8", "utf8", "all-bytes"),
)
def test_python2_interned_bytes_match_ordinary_strings(version, value):
    ordinary = reader(string_record(b"s", value), version).r_object(bytes_for_s=True)
    interned = reader(string_record(b"t", value), version).r_object(bytes_for_s=True)
    assert isinstance(interned, bytes)
    assert ordinary == interned == value


@pytest.mark.parametrize("version", ("2.4", "2.7"))
@pytest.mark.parametrize("first_bytes", (False, True))
@pytest.mark.parametrize(
    "raw, text", ((b"shared_value", "shared_value"), (b"\xffA\x80", "A"))
)
def test_python2_references_preserve_both_representations(
    version, first_bytes, raw, text
):
    reference = b"R" + pack("<i", 0)
    unmarshaler = reader(string_record(b"t", raw) + reference * 2, version)
    first = unmarshaler.r_object(bytes_for_s=first_bytes)
    other = unmarshaler.r_object(bytes_for_s=not first_bytes)
    repeated = unmarshaler.r_object(bytes_for_s=first_bytes)
    assert first == (raw if first_bytes else text)
    assert other == (text if first_bytes else raw)
    assert repeated is first


def test_python2_interned_tuple_from_cpython():
    # CPython 2.7.18: value = intern('\xffA\x80'); marshal.dumps((value, value), 2)
    data = bytes.fromhex("28020000007403000000ff41805200000000")
    result = reader(data).r_object(bytes_for_s=True)
    assert result == (b"\xffA\x80", b"\xffA\x80")
    assert result[0] is result[1]


@pytest.mark.parametrize("bytes_for_s", (False, True))
@pytest.mark.parametrize(
    "version, tag, text",
    (
        ("3.3", b"t", "\u00e9"),
        ("3.4", b"t", "\u00e9"),
        ("3.4", b"A", "shared_value"),
        ("3.4", b"Z", "shared_value"),
    ),
)
def test_python3_interned_strings_remain_text(version, tag, text, bytes_for_s):
    result = reader(string_record(tag, text.encode("utf8")), version).r_object(
        bytes_for_s=bytes_for_s
    )
    assert isinstance(result, str)
    assert result == text


@pytest.mark.parametrize("bytes_for_s", (False, True))
def test_python3_object_references_remain_text(bytes_for_s):
    data = (
        string_record(bytes([ord("t") | 0x80]), b"shared_value") + b"r" + pack("<i", 0)
    )
    unmarshaler = reader(data, "3.4")
    first = unmarshaler.r_object(bytes_for_s=bytes_for_s)
    second = unmarshaler.r_object(bytes_for_s=bytes_for_s)
    assert first == "shared_value"
    assert isinstance(first, str)
    assert second is first


@pytest.mark.parametrize("code_tag", (b"s", b"t"))
def test_python27_pyc_keeps_interned_bytecode_and_text_metadata(code_tag):
    # Generated by stock CPython 2.7.18: compile('fn(*args)', '<fixture>', 'exec'),
    # rebuild using types.CodeType with intern(co.co_code), then marshal.dumps(co, 2).
    # CALL_FUNCTION_VAR (0x8c) is not valid standalone UTF-8. The other variant
    # uses the ordinary string tag for the same bytecode.
    data = bytes.fromhex(
        "6300000000000000000200000040000000740e0000006500006501008c00000164000053"
        "28010000004e28020000007402000000666e74040000006172677328000000002800000000"
        "280000000073090000003c666978747572653e74080000003c6d6f64756c653e01000000"
        "7400000000"
    )
    data = data[:17] + code_tag + data[18:]
    pyc = by_version["2.7"] + pack("<I", 0) + data
    version, _, _, code, *_ = load_module_from_file_object(io.BytesIO(pyc))
    expected = bytes.fromhex("6500006501008c00000164000053")
    assert version == (2, 7)
    assert code.co_code == expected
    assert isinstance(code.co_code, bytes)
    assert code.co_consts == (None,)
    assert code.co_names == ("fn", "args")
    assert code.co_filename == "<fixture>"
    assert code.co_name == "<module>"

    # Keep the reference metadata used by the marshal writer, for both bytecode
    # and textual names. No interpreter or filesystem fixture is required.
    dumped = dumps(code, python_version=(2, 7))
    assert dumped[17:18] == code_tag
    assert string_record(b"t", b"fn") in dumped
    restored = load_code(dumped, magic2int(by_version["2.7"]), code_objects={})
    assert restored.co_code == expected
    assert restored.co_names == code.co_names
